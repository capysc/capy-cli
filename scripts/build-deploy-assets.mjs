#!/usr/bin/env node
// Regenerates src/ui/deployPage/generatedAssets.ts — compiled Tailwind CSS
// for the deploy page, fetched via `npx --yes tailwindcss@3.4` (NOT a
// package dep).
//
// Run: npm run build:deploy-assets
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync, rmSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const pkgRoot = resolve(__dirname, '..');

const input = resolve(pkgRoot, 'src/ui/deployPage/input.css');
const tmpOut = resolve(pkgRoot, 'src/ui/deployPage/.tailwind.out.css');
const config = resolve(pkgRoot, 'tailwind.config.js');

execSync(
  `npx --yes tailwindcss@3.4 -c "${config}" -i "${input}" -o "${tmpOut}" --minify`,
  { cwd: pkgRoot, stdio: 'inherit' },
);

const tailwindCss = readFileSync(tmpOut, 'utf8').trim();

const ts =
  `// AUTO-GENERATED by scripts/build-deploy-assets.mjs. Do not edit by hand.\n` +
  `// Regenerate with: npm run build:deploy-assets\n` +
  `// Contains: compiled Tailwind CSS for the deploy page.\n` +
  `\n` +
  `export const DEPLOY_PAGE_CSS = ${JSON.stringify(tailwindCss)};\n`;

writeFileSync(resolve(pkgRoot, 'src/ui/deployPage/generatedAssets.ts'), ts);
rmSync(tmpOut);

const sizeKb = (tailwindCss.length / 1024).toFixed(1);
console.log(`Wrote src/ui/deployPage/generatedAssets.ts (${sizeKb} KB inline CSS)`);
