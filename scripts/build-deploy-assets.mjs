#!/usr/bin/env node
// Regenerates src/ui/deployPage/generatedAssets.ts from:
//   - Tailwind CSS compiled against the deploy-page template (fetched via
//     `npx --yes tailwindcss@3.4`; NOT a package dep)
//   - Geist font files (assets/fonts/*.woff2) base64-inlined as @font-face
//
// Run: npm run build:deploy-assets
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync, rmSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const pkgRoot = resolve(__dirname, '..');

const FONTS = [
  { weight: 400, file: 'Geist-Regular.woff2' },
  { weight: 500, file: 'Geist-Medium.woff2' },
  { weight: 600, file: 'Geist-SemiBold.woff2' },
];

const input = resolve(pkgRoot, 'src/ui/deployPage/input.css');
const tmpOut = resolve(pkgRoot, 'src/ui/deployPage/.tailwind.out.css');
const config = resolve(pkgRoot, 'tailwind.config.js');

execSync(
  `npx --yes tailwindcss@3.4 -c "${config}" -i "${input}" -o "${tmpOut}" --minify`,
  { cwd: pkgRoot, stdio: 'inherit' },
);

const tailwindCss = readFileSync(tmpOut, 'utf8').trim();

const fontFaces = FONTS.map(({ weight, file }) => {
  const buf = readFileSync(resolve(pkgRoot, 'assets/fonts', file));
  const b64 = buf.toString('base64');
  return `@font-face{font-family:'Geist';font-style:normal;font-weight:${weight};font-display:swap;src:url(data:font/woff2;base64,${b64}) format('woff2')}`;
}).join('\n');

const combined = `${fontFaces}\n${tailwindCss}`;

const ts =
  `// AUTO-GENERATED by scripts/build-deploy-assets.mjs. Do not edit by hand.\n` +
  `// Regenerate with: npm run build:deploy-assets\n` +
  `// Contains: Geist @font-face (base64 woff2) + compiled Tailwind CSS for the deploy page.\n` +
  `//\n` +
  `// Geist font © 2024 The Geist Project Authors, licensed under the SIL Open Font\n` +
  `// License v1.1 — see assets/fonts/OFL.txt.\n` +
  `\n` +
  `export const DEPLOY_PAGE_CSS = ${JSON.stringify(combined)};\n`;

writeFileSync(resolve(pkgRoot, 'src/ui/deployPage/generatedAssets.ts'), ts);
rmSync(tmpOut);

const sizeKb = (combined.length / 1024).toFixed(1);
console.log(`Wrote src/ui/deployPage/generatedAssets.ts (${sizeKb} KB inline CSS)`);
