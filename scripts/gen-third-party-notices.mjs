// Regenerates THIRD-PARTY-NOTICES.md for the packages the prebuilt binaries
// actually embed. Their MIT / ISC / BSD / Apache licenses all ask for the same
// thing in exchange for the code: ship the copyright notice with it.
//
// The package list comes from an esbuild metafile rather than package.json, so
// it tracks what is really in the bundle — including tree-shaking (declared
// deps that contribute nothing are left out) and packages reached by a bare
// `require()` without being declared.
//
// Usage: node scripts/gen-third-party-notices.mjs [--check]
//   --check exits non-zero if the committed file is stale.
import { build } from 'esbuild';
import { readFile, writeFile, readdir, stat } from 'fs/promises';
import { fileURLToPath } from 'url';
import path from 'path';
import { bundleOptions } from '../build.esbuild.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const cliDir = path.resolve(here, '..');
const outFile = path.join(cliDir, 'THIRD-PARTY-NOTICES.md');

const LICENSE_FILE = /^licen[cs]e(\.|$)/i;
const NOTICE_FILE = /^notice(\.|$)/i;

/** node_modules/<name>/rest → the directory holding that package's manifest. */
function packageDirFromInput(inputPath) {
  const parts = inputPath.split(path.sep);
  const idx = parts.lastIndexOf('node_modules');
  if (idx === -1) return null;
  const scoped = parts[idx + 1]?.startsWith('@');
  const end = idx + (scoped ? 3 : 2);
  if (parts.length < end) return null;
  return parts.slice(0, end).join(path.sep);
}

async function bundledPackageDirs() {
  const result = await build({
    ...bundleOptions,
    write: false,
    metafile: true,
    outfile: path.join(cliDir, 'build', 'notices-probe.cjs'),
  });

  const dirs = new Set();
  for (const input of Object.keys(result.metafile.inputs)) {
    const dir = packageDirFromInput(path.resolve(cliDir, input));
    if (dir) dirs.add(dir);
  }
  return [...dirs];
}

async function readTextFile(dir, match) {
  const entries = await readdir(dir).catch(() => []);
  const hit = entries.find((e) => match.test(e));
  if (!hit) return null;
  const target = path.join(dir, hit);
  if (!(await stat(target)).isFile()) return null;
  return (await readFile(target, 'utf8')).trim();
}

async function collect() {
  const packages = [];
  for (const dir of await bundledPackageDirs()) {
    const manifest = JSON.parse(
      await readFile(path.join(dir, 'package.json'), 'utf8'),
    );
    packages.push({
      name: manifest.name,
      version: manifest.version,
      license: manifest.license ?? '(see license text)',
      homepage: manifest.homepage ?? null,
      licenseText: await readTextFile(dir, LICENSE_FILE),
      noticeText: await readTextFile(dir, NOTICE_FILE),
    });
  }
  return packages.sort((a, b) => a.name.localeCompare(b.name));
}

function render(packages) {
  const licenses = [...new Set(packages.map((p) => p.license))].sort();
  const lines = [
    '# Third-party notices',
    '',
    'The Capy CLI is distributed both as an npm package and as prebuilt standalone',
    'binaries. The binaries embed the packages listed below, plus a Node.js runtime',
    '(https://github.com/nodejs/node/blob/main/LICENSE), directly into the executable.',
    'Their copyright notices and license terms are reproduced here in full.',
    '',
    'Capy itself is licensed under AGPL-3.0-only; see LICENSE. Nothing below changes',
    "the license of Capy, and Capy's license does not change the terms below.",
    '',
    'Generated by `scripts/gen-third-party-notices.mjs` from the esbuild bundle —',
    `${packages.length} packages, licensed under ${licenses.join(', ')}.`,
    '',
    '## Packages',
    '',
    '| Package | Version | License |',
    '| --- | --- | --- |',
    ...packages.map((p) => `| ${p.name} | ${p.version} | ${p.license} |`),
    '',
    '## License texts',
    '',
  ];

  for (const p of packages) {
    lines.push(`### ${p.name}@${p.version}`, '');
    if (p.homepage) lines.push(p.homepage, '');
    lines.push('```');
    lines.push(
      p.licenseText ?? `${p.license} — no license file shipped in the package.`,
    );
    lines.push('```', '');
    if (p.noticeText) {
      lines.push(`#### NOTICE (${p.name})`, '', '```', p.noticeText, '```', '');
    }
  }

  return lines.join('\n');
}

async function main() {
  const rendered = render(await collect());
  if (process.argv.includes('--check')) {
    const existing = await readFile(outFile, 'utf8').catch(() => null);
    if (existing !== rendered) {
      console.error(
        'THIRD-PARTY-NOTICES.md is out of date. Run: bun run notices',
      );
      process.exit(1);
    }
    console.log('THIRD-PARTY-NOTICES.md is up to date.');
    return;
  }
  await writeFile(outFile, rendered);
  console.log(`Wrote ${outFile}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
