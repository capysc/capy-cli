#!/usr/bin/env node
// Regenerates src/ui/screens/generated.ts and src/ui/screens/contract.ts from
// the monorepo ui/fixtures packages. Follows the same committed-generated-file
// pattern as build-deploy-assets.mjs, so standalone clones of this repo build
// and release without the monorepo present.
//
// Run from a capy monorepo checkout (this repo mounted at packages/cli):
//   bun run --cwd packages/ui build        # produce ../ui/dist
//   bun run --cwd packages/cli build:screens
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { dirname, resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const pkgRoot = resolve(__dirname, '..');
const uiDist = resolve(pkgRoot, '../ui/dist/screens');
const contractSrc = resolve(pkgRoot, '../fixtures/src/contract.ts');

if (!existsSync(uiDist)) {
  console.error(`Missing ${uiDist} — run \`bun run --cwd packages/ui build\` in the monorepo first.`);
  process.exit(1);
}

const screens = readdirSync(uiDist).sort();
const entries = [];
for (const screen of screens) {
  const htmlPath = join(uiDist, screen, 'index.html');
  if (!existsSync(htmlPath)) continue;
  const html = readFileSync(htmlPath, 'utf8');
  if (!html.includes('/*__CAPY_DATA__*/ null')) {
    console.error(`${screen}: built HTML is missing the __CAPY_DATA__ placeholder`);
    process.exit(1);
  }
  entries.push([screen, html]);
}

if (entries.length === 0) {
  console.error('No built screens found.');
  process.exit(1);
}

/**
 * Which screens take the wide measure.
 *
 * The CLI has to size a chromeless browser window BEFORE that window has
 * loaded anything, so the answer has to be known from the name alone. Read
 * from the authored `Screen.svelte` rather than the built HTML because
 * `class:wide` compiles to a runtime expression and leaves nothing static to
 * look for.
 *
 * Unclassifiable is a build failure, not a default. A screen that quietly got
 * `false` here is a four-column secret table wrapping variable names mid-word
 * in a 520px window — the exact defect that put `wide` on `Page` to begin
 * with, arriving a second time through a silent fallback.
 */
/**
 * The open tags of a screen's root layout elements, brace-aware.
 *
 * `<Page[^>]*>` is the obvious way to do this and it is wrong SILENTLY, which
 * is worse than being wrong loudly: `deploy-tokens` writes
 * `subtitle={data.tokens.length > 0 ? … }` inside its `<Page>`, so the naive
 * match ends the tag at that comparison, never reaches the `wide` two lines
 * below it, and sizes a token listing like a yes/no question. Counting braces
 * is what makes the `>` inside an expression not a tag terminator.
 */
function rootTags(src) {
  const tags = [];
  const re = /<(?:Page|Wizard)\b/g;
  let m;
  while ((m = re.exec(src))) {
    let depth = 0;
    for (let i = m.index; i < src.length; i++) {
      const c = src[i];
      if (c === '{') depth++;
      else if (c === '}') depth--;
      else if (c === '>' && depth === 0) {
        tags.push(src.slice(m.index, i + 1));
        break;
      }
    }
  }
  return tags;
}

const uiScreens = resolve(pkgRoot, '../ui/screens');
const wide = {};
for (const [screen] of entries) {
  const sveltePath = join(uiScreens, screen, 'Screen.svelte');
  if (!existsSync(sveltePath)) {
    console.error(`${screen}: built, but has no Screen.svelte to read its measure from`);
    process.exit(1);
  }
  // A screen's root is `Page`, or `Wizard` — which is a `Page` with a rail and
  // forwards `wide` straight through to it. Read the OPEN TAG rather than the
  // file: `connect-overwrite` has the word "wide" in a comment about a table
  // column, `invite-teammate` and `member-branch-access` say `org-wide` about
  // a role, and a whole-file grep calls all three wide.
  const roots = rootTags(readFileSync(sveltePath, 'utf8'));
  if (!roots.length) {
    console.error(`${screen}: no <Page> or <Wizard> element — every screen renders inside one`);
    process.exit(1);
  }
  // Any root that CAN be wide makes the screen wide. `sync-conflict` is the
  // case: `wide={step === 'review'}`, narrow while it asks and wide once it
  // shows the diff. The window is opened once, before the first render, so it
  // has to be sized for the widest thing that flow can become — a window with
  // spare margin costs nothing, and one that is too narrow wraps the table
  // that made someone reach for `wide` in the first place.
  wide[screen] = roots.some((tag) => /\bwide\b/.test(tag));
}

const header = (source) =>
  `// AUTO-GENERATED by scripts/build-screen-assets.mjs. Do not edit by hand.\n` +
  `// Source of truth: ${source} (capy monorepo).\n` +
  `// Regenerate with: bun run build:screens (from a monorepo checkout).\n\n`;

const generated =
  header('packages/ui — built by Vite to self-contained per-screen HTML') +
  `import type { ScreenName } from './contract';\n\n` +
  `export const SCREEN_HTML: Record<ScreenName, string> = {\n` +
  entries.map(([name, html]) => `  '${name}': ${JSON.stringify(html)},\n`).join('') +
  `};\n\n` +
  `/** True where the screen renders inside \`<Page wide>\`. See the generator. */\n` +
  `export const SCREEN_WIDE: Record<ScreenName, boolean> = {\n` +
  entries.map(([name]) => `  '${name}': ${wide[name]},\n`).join('') +
  `};\n`;
writeFileSync(resolve(pkgRoot, 'src/ui/screens/generated.ts'), generated);

const contract = readFileSync(contractSrc, 'utf8');
writeFileSync(
  resolve(pkgRoot, 'src/ui/screens/contract.ts'),
  header('packages/fixtures/src/contract.ts') + contract,
);

for (const [name, html] of entries) {
  console.log(`embedded ${name}: ${(html.length / 1024).toFixed(1)} KB`);
}
