/**
 * Writes `.capy/next-env.js`, a CommonJS module mapping each decrypted env var
 * name to a `process.env[KEY]` reference. Users import it in next.config.js:
 *
 *   const capyEnv = require('./.capy/next-env');
 *   module.exports = { env: capyEnv };
 *
 * At `next build` time Next.js inlines each value as a string literal into the
 * compiled bundle, so the secrets are available in Edge, Node, or any runtime
 * without needing Capy at runtime.
 */
function emitNextEnvModule(keys: string[]): void {
  const capyDir = join(process.cwd(), '.capy');
  mkdirSync(capyDir, { recursive: true });

  const body = keys
    .map((k) => `  ${JSON.stringify(k)}: process.env[${JSON.stringify(k)}]`)
    .join(',\n');

  const content =
    `// Auto-generated by capy run. Do not edit.\n` +
    `module.exports = {\n${body}\n};\n`;

  writeFileSync(join(capyDir, 'next-env.js'), content, 'utf-8');
}

/**
 * Final-gate BLOCKER-1(c): `keyResolver.unwrapMasterKey` throws
 * PERMISSION_DENIED — with no `details.status` (a client-local decision, not
 * a server 403) — whenever there is no usable key.enc on this machine. Its
 * message only ever names one remedy, "ask the project owner to invite
 * you". That's correct for a teammate who was never granted access, but it
 * is the wrong (or at least incomplete) remedy for a machine that could
 * instead unlock via an already-enrolled device key — the whole point of
 * the device-key feature is to make that remedy unnecessary. Named "device
 * key" per invariant 9 either way, whether or not the retry above got a
 * chance to run.
 */
function missingKeyRemediation(deviceKeysEnabled: boolean): CapyError {
  const lines = [
    "You do not have access to this project's secrets on this device.",
    '',
    '  Ask the project owner to invite you, then run:',
    '',
    '    capy redeem <code>',
  ];
  if (deviceKeysEnabled) {
    lines.push(
      '',
      '  Or, if this account already has a device key enrolled on another',
      '  machine, approve this device there (a device-key unlock was just',
      '  attempted and did not complete) and re-run this command.',
    );
  } else {
    lines.push(
      '',
      '  Or, if this account already has a device key enrolled on another',
      '  machine, set CAPY_DEVICE_KEYS=1 and re-run — this device will try to',
      '  unlock automatically instead of waiting on an invite.',
    );
  }
  return new CapyError(lines.join('\n'), ERROR_CODES.PERMISSION_DENIED);
}

/**
 * Spawns the child process with the provided environment, forwards signals,
 * and resolves with its exit code. Shared between local and deployed modes.
 *
 * Reserved runtime variables are stripped HERE rather than at each call site
 * (CAP-423). This is the single chokepoint every mode funnels through, so a
 * future spawn path cannot forget to strip: the deploy credentials are
 * consumed by the time we get here, and the child is precisely the process
 * whose environment leaks — debug pages, `phpinfo()`, error-tracker SDKs that
 * capture env by default, `/proc/<pid>/environ`, crash dumps — with every
 * grandchild inheriting whatever we pass.
 */
function spawnChild(args: string[], env: Record<string, string | undefined>): Promise<number> {
  let child: ChildProcess | null = null;
  for (const sig of ['SIGTERM', 'SIGINT', 'SIGHUP'] as const) {
    process.on(sig, () => child?.kill(sig));
  }

  // On Windows, node_modules/.bin entries are .cmd shims that Node's spawn
  // won't execute without a shell — bare `cross-env`/`nodemon` fail with
  // ENOENT. shell:true delegates to cmd.exe so PATHEXT resolution kicks in.
  child = spawn(args[0], args.slice(1), {
    env: stripReservedRuntimeVars(env) as Record<string, string>,
    stdio: 'inherit',
    shell: process.platform === 'win32',
  });

  return new Promise((resolve) => {
    child!.on('error', (err) => {
      console.error(`capy run: ${err.message}`);
      resolve(1);
    });
    child!.on('close', (code) => resolve(code ?? 1));
  });
}

export async function runCommand(args: string[], devMode: boolean = false): Promise<number> {
  if (args.length === 0) {
    console.error('Usage: capy run -- <command> [args...]');
    return 1;
  }

  // Deploy-credential selection (CAP-411/CAP-424): the variable NAME is the
  // only discriminator, never the value. DT (current-generation) and PK
  // (legacy) are both 32 random bytes rendered as 64-char hex — structurally
  // indistinguishable as values, so there is no length check, no charset
  // check, and no trial decryption (Rule 4: branch on a stable signal, never
  // by trying a value and seeing what happens — that is both a prose-parsing
  // analog and a silent-fallback footgun).
  //
  //   both current-generation vars present  → DT path
  //   both legacy vars present              → legacy PK path
  //   neither pair present                  → local mode
  //   anything else (half-set pair, both
  //     generations at once, or a cross-
  //     generation mix)                     → hard, loud error
  const currentBlob = process.env[CURRENT_SECRETS_BLOB_VAR];
  const currentKey = process.env[CURRENT_DEPLOY_KEY_VAR];
  const legacyBlob = process.env[LEGACY_SECRETS_BLOB_VAR];
  const legacyKey = process.env[LEGACY_PROJECT_KEY_VAR];

  const currentCount = (currentBlob ? 1 : 0) + (currentKey ? 1 : 0);
  const legacyCount = (legacyBlob ? 1 : 0) + (legacyKey ? 1 : 0);

  const deployMode: 'dt' | 'legacy' | 'local' | 'error' =
    currentCount === 2 && legacyCount === 0
      ? 'dt'
      : legacyCount === 2 && currentCount === 0
        ? 'legacy'
        : currentCount === 0 && legacyCount === 0
          ? 'local'
          : 'error';

  if (deployMode === 'error') {
    console.error(
      'capy run: ambiguous deploy credentials in the environment. Expected exactly one ' +
        `complete pair — either ${CURRENT_SECRETS_BLOB_VAR} + ${CURRENT_DEPLOY_KEY_VAR} ` +
        `(current) or ${LEGACY_SECRETS_BLOB_VAR} + ${LEGACY_PROJECT_KEY_VAR} (legacy) — or ` +
        'neither, for local mode. Got a half-set pair, both generations at once, or a ' +
        'cross-generation mix. Refusing to guess which one you meant.',
    );
    return 1;
  }

  // Deployed mode: CI, serverless, Vercel builds, etc.
  if (deployMode === 'dt' || deployMode === 'legacy') {
    const { parseSecretsBlob, fetchDeployDecryptMaterial, decryptSecretsBlob } = await import(
      '../crypto/deployRuntime'
    );

    let envMap: Record<string, string>;
    try {
      const blob = deployMode === 'dt' ? currentBlob! : legacyBlob!;
      const { deployId, outerBlob, encryptedVars } = parseSecretsBlob(blob);
      const apiUrl = process.env.CAPY_API_URL ?? 'https://api.capy.sc';
      debug('capy run: fetching deploy key...');
      const material = await fetchDeployDecryptMaterial(
        apiUrl,
        deployId.toString('hex'),
        outerBlob.toString('base64'),
      );

      let projectKeyHex: string;
      if (deployMode === 'dt') {
        // DT path (CAP-411): recover PK in memory from the service's
        // KMS-unwrapped inner blob + the DT this deploy target holds. Nothing
        // on disk or in the environment ever holds PK itself.
        const { deployInnerUnwrap } = await import('../crypto/deployCrypto');
        const pk = deployInnerUnwrap(material.innerBlob, Buffer.from(currentKey!, 'hex'), material.projectId);
        projectKeyHex = pk.toString('hex');
      } else {
        projectKeyHex = legacyKey!;
      }

      envMap = decryptSecretsBlob(encryptedVars, projectKeyHex, material.serviceKey, deployId);
    } catch (err: any) {
      console.error(`capy run: ${err.message}`);
      return 1;
    }

    // Auto-emit .capy/next-env.js for Next.js build-time inlining. Best-effort
    // — failure to write is non-fatal (e.g., read-only FS in exotic envs).
    try {
      emitNextEnvModule(Object.keys(envMap));
    } catch {
      // No-op. next-env.js is a convenience; the child still gets the env.
    }

    // dotenv precedence: pre-existing process.env wins over the decrypted
    // values. Shell overrides stay sovereign.
    const childEnv = { ...envMap, ...process.env };
    return spawnChild(args, childEnv);
  }

  // Local mode: read .env from CWD, then resolve the project key via the
  // server's co-decrypt endpoint so every decryption is audit-logged. No
  // local key caching, no CAPY_KEY escape hatch — server must be reachable.
  const fm = new FileManager();
  const envFromFile = fm.readEnvFile();

  // Collect encrypted entries from .env *before* the shell merge. An
  // encrypted value represents a deliberate project secret, so it must not be
  // silently overridden by a stale value of the same name in process.env
  // (common when the user has an unrelated DATABASE_URL etc. in their shell).
  const toDecrypt: Array<[string, string]> = [];
  for (const [k, v] of Object.entries(envFromFile)) {
    if (typeof v === 'string' && fm.isEncrypted(v)) {
      toDecrypt.push([k, v]);
    }
  }

  // Merge plaintext keys with dotenv precedence (shell wins). Encrypted keys
  // are re-applied after decryption below, so they always win regardless of
  // what process.env contains.
  const env: Record<string, string | undefined> = { ...envFromFile, ...process.env };

  if (toDecrypt.length === 0) {
    // CAP-487: an .env with plaintext values and NOTHING encrypted is not
    // the ordinary mid-state of an onboarded repo (a new key awaiting a push
    // rides alongside encrypted ones and lands in `toDecrypt` above) — it is
    // what a repo looks like when onboarding never finished. Passing the
    // values through with exit 0 was a false-green: `capy run` appeared to
    // decrypt when it decrypted nothing, and an agent reading the exit code
    // concluded the repo was set up. Branching is on stable local signals
    // only — file existence and the structural isEncrypted check, never
    // value content.
    const keepLockPresent = existsSync(join(process.cwd(), 'keep.lock'));
    if (Object.keys(envFromFile).length > 0) {
      if (!keepLockPresent) {
        console.error(
          `capy run: [${ERROR_CODES.NOT_ONBOARDED}] the .env here is plaintext and this ` +
            'directory is not onboarded (no keep.lock) — nothing would be decrypted. ' +
            'Run `capy` here to finish onboarding, or run your command directly if you ' +
            'did not mean to use Capy in this directory.',
        );
        return 1;
      }
      // Onboarded (keep.lock present) but the whole .env is plaintext: run,
      // but say out loud that no decryption happened.
      console.error(
        'capy run: warning — .env has no encrypted values; passing plaintext through unchanged.',
      );
    } else if (keepLockPresent) {
      // keep.lock with NO variables at all is the other false-green twin of
      // the plaintext case above: a fresh clone before any branch is selected
      // used to spawn the child silently with zero injection and exit 0, so a
      // script believed secrets were delivered when none were. Same stable
      // local signals as everywhere else — file existence and the derived
      // branch state, never message text or value content.
      const { ProjectManager } = await import('../core/projectManager');
      const activeBranch = new ProjectManager().deriveActiveBranch();
      if (!activeBranch) {
        console.error(
          `capy run: [${ERROR_CODES.NO_ACTIVE_BRANCH}] this directory is onboarded ` +
            '(keep.lock present) but no secret branch is active and no .env is ' +
            'materialized — nothing would be injected. Run `capy checkout <branch>` ' +
            '(or `capy`) to select a branch first.',
        );
        return 1;
      }
      // A selected branch can legitimately hold zero variables; run, but say
      // out loud that nothing was injected.
      console.error(
        `capy run: warning — branch "${activeBranch}" has no variables materialized in .env; ` +
          'running with no injected secrets.',
      );
    }
    // Pure plaintext .env — no key required.
    return spawnChild(args, env);
  }

  const keepPath = join(process.cwd(), 'keep.lock');
  let orgId: string | undefined;
  let projectId: string | undefined;
  if (existsSync(keepPath)) {
    try {
      const keep = JSON.parse(readFileSync(keepPath, 'utf-8'));
      orgId = keep?.org_id;
      projectId = keep?.project_id;
    } catch {
      console.error('capy run: keep.lock is malformed. Run `capy` to re-sync.');
      return 1;
    }
    if (!orgId || !projectId) {
      console.error('capy run: keep.lock missing org_id/project_id. Run `capy` to re-sync.');
      return 1;
    }
  } else {
    // Single-user lock-less mode: no keep.lock in this directory. Identity comes
    // from the `.env` header a previous lock-less `capy add`/`capy edit` run
    // wrote (`# capy:org_id=…` / `# capy:project_id=…`) — the same header
    // `resolveContext()` reads in connectors/shared.ts. Key resolution below
    // (resolveProjectKey / co-decrypt / local-only passphrase) is completely
    // unchanged either way, including its own pre-existing offline
    // project-key cache fallback (keyResolver.ts's readProjectKeyCache /
    // isNetworkError) — lock-less mode needs no separate content cache here
    // because the encrypted secret content itself is already local, in this
    // `.env` file; only the key to decrypt it can require the network.
    const meta = fm.readEnvMeta();
    orgId = meta.org_id;
    projectId = meta.project_id;
    if (!orgId || !projectId) {
      console.error(
        'capy run: no keep.lock and no Capy identity in .env. Run `capy add` here first.',
      );
      return 1;
    }
  }

  // Definite-assignment: every non-throwing path through the try block below
  // assigns this before use — TS's control-flow analysis can't see through
  // the nested try/catch/if the device-key retry (BLOCKER-1(c)) requires.
  let projectKeyHex!: string;
  try {
    const { isLocalOnly } = await import('../config/profileConfig');

    // Local-only mode: resolve the key entirely offline from the passphrase
    // session — no auth, no ServiceClient, no co-decrypt. Prompts for the
    // passphrase on demand if the session is locked, so `capy run` always
    // works even after `capy lock`.
    if (isLocalOnly()) {
      const { resolveLocalProjectKey } = await import('../core/localUnlock');
      projectKeyHex = await resolveLocalProjectKey(projectId);
    } else {
      const { AuthService, silentAuthFailureMessage } = await import('../auth/authService');
      const { ServiceClient } = await import('../service/serviceClient');
      const { resolveProjectKey } = await import('../crypto/keyResolver');

      const auth = new AuthService(undefined, devMode);
      const result = await auth.authenticateSilent(orgId);
      if (!result.success || !result.user_id) {
        console.error(`capy run: ${silentAuthFailureMessage(result)}`);
        return 1;
      }

      const svc = new ServiceClient(undefined, devMode);
      svc.setTokenProvider(() => auth.getValidToken());
      const keyServiceOps = {
        coDecrypt: (o: string, c: string) => svc.coDecrypt(o, c).then(r => r.plaintext),
        wrapOuterLayer: (o: string, p: string) => svc.wrapOuterLayer(o, p).then(r => r.ciphertext),
      };

      try {
        projectKeyHex = await resolveProjectKey(orgId, projectId, result.user_id, keyServiceOps);
      } catch (keyErr) {
        // Final-gate BLOCKER-1(c): a missing/invalid key.enc used to dead-end
        // straight into "ask for an invite" with no device-key path at all —
        // even with CAPY_DEVICE_KEYS=1 and a live door this account could
        // unlock from. keyResolver.ts is untouched (invariant 4 depends on
        // it staying that way); the branch lives entirely here, keyed off
        // the coded PERMISSION_DENIED keyResolver already throws, never off
        // its message text.
        const isMissingKey = keyErr instanceof CapyError && keyErr.code === ERROR_CODES.PERMISSION_DENIED;
        if (!isMissingKey) throw keyErr;

        const { deviceKeysEnabled } = await import('../auth/deviceKey/flag');
        const enabled = deviceKeysEnabled();
        let unlocked = false;
        if (enabled) {
          // CAP-384: a sandbox that has an active per-chat grant MUST NOT
          // fall through to attemptCaseCUnlock below — that path durably
          // writes local.key + key.enc for every org this account belongs
          // to, exactly the persistent-key-on-ephemeral-infra defect the
          // grant exists to prevent (final-gate.md §1.4 item 5). So when the
          // ephemeral signal is present, the grant is the ONLY path tried;
          // its own failure (never granted, or expired) surfaces as a coded
          // remediation instead of silently degrading to a durable unlock.
          const { configuredGrantSocketPath } = await import('../auth/deviceKey/ephemeral');
          const grantSocket = configuredGrantSocketPath();
          if (grantSocket) {
            const { fetchGrantedKLocal } = await import('../auth/deviceKey/grantHolder');
            const { resolveProjectKeyFromGrant, createGrantResolutionOps } = await import('../auth/deviceKey/grantResolver');
            let grant;
            try {
              grant = await fetchGrantedKLocal(grantSocket, result.user_id);
            } catch (grantErr) {
              // EXIT_NEEDS_INPUT (3), not the generic failure exit (1): a
              // missing/expired grant needs a human (or the orchestrating
              // agent) to re-run `capy device-key grant` — a coded signal an
              // MCP caller can branch on, never message text (Rule 4).
              const code =
                grantErr instanceof CapyError && grantErr.code === ERROR_CODES.DEVICE_KEY_GRANT_EXPIRED
                  ? ERROR_CODES.DEVICE_KEY_GRANT_EXPIRED
                  : ERROR_CODES.DEVICE_KEY_GRANT_NOT_FOUND;
              console.error(`\ncapy run: [${code}] ${grantErr instanceof Error ? grantErr.message : String(grantErr)}`);
              console.error('  Re-run `capy device-key grant` for this chat, then try again.\n');
              process.exit(EXIT_NEEDS_INPUT);
            }
            const grantOps = createGrantResolutionOps(svc, auth);
            projectKeyHex = await resolveProjectKeyFromGrant(grant.kLocal, orgId, projectId, result.user_id, grantOps);
            unlocked = true;
          } else {
            // attemptCaseCUnlock does its own "does this account have live
            // doors" detection internally (via detectOnboardingCase) — it is
            // a safe no-op, never a throw, when there is nothing to unlock
            // with.
            const { attemptCaseCUnlock, attemptPickupConsumption } = await import('../auth/deviceKey/wiring');
            const wiringCtx = {
              authService: auth,
              serviceClient: svc,
              devMode,
              userId: result.user_id,
              userEmail: result.user_email,
              organizations: result.organizations || [],
              activeOrgId: orgId,
            };
            const unlock = await attemptCaseCUnlock(wiringCtx);
            if (unlock.ok) {
              try {
                // Retry once now that the unlock ceremony may have installed
                // key.enc for this org.
                projectKeyHex = await resolveProjectKey(orgId, projectId, result.user_id, keyServiceOps);
                unlocked = true;
              } catch {
                unlocked = false;
              }
            }
            // attemptCaseCUnlock above is a no-op for a brand-new
            // invitee (no live doors yet) — exactly the account state a Keep
            // pickup paste leaves them in. Try consuming any pending pickup
            // before falling through to missingKeyRemediation below. Additive
            // and side-effect-free when there is nothing pending: same
            // never-throws contract as attemptCaseCUnlock (see wiring.ts).
            if (!unlocked) {
              const pickup = await attemptPickupConsumption(wiringCtx);
              if (pickup.ok) {
                try {
                  projectKeyHex = await resolveProjectKey(orgId, projectId, result.user_id, keyServiceOps);
                  unlocked = true;
                } catch {
                  unlocked = false;
                }
              }
            }
          }
        }
        if (!unlocked) throw missingKeyRemediation(enabled);
      }
    }
  } catch (err: any) {
    console.error(`capy run: failed to resolve project key: ${err.message}`);
    return 1;
  }

  // Decrypt into a buffer first so we never partially mutate env.
  const decrypted: Array<[string, string]> = [];
  for (const [k, v] of toDecrypt) {
    try {
      decrypted.push([k, fm.decryptValue(v, projectKeyHex)]);
    } catch (err: any) {
      console.error(`capy run: failed to decrypt "${k}": ${err.message}`);
      return 1;
    }
  }

  for (const [k, v] of decrypted) env[k] = v;
  return spawnChild(args, env);
}
